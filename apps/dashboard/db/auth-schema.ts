export const media = pgTable("media", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  slug: text("slug").notNull().unique(),
  logo: text("logo"),
  createdAt: timestamp("created_at").notNull(),
  metadata: text("metadata"),
});

export const membership = pgTable(
  "membership",
  {
    id: text("id").primaryKey(),
    organizationId: text("organization_id")
      .notNull()
      .references(() => media.id, { onDelete: "cascade" }),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    role: text("role").default("member").notNull(),
    createdAt: timestamp("created_at").notNull(),
  },
  (table) => [
    index("membership_organizationId_idx").on(table.organizationId),
    index("membership_userId_idx").on(table.userId),
  ],
);

export const mediaInvitation = pgTable(
  "media_invitation",
  {
    id: text("id").primaryKey(),
    organizationId: text("organization_id")
      .notNull()
      .references(() => media.id, { onDelete: "cascade" }),
    email: text("email").notNull(),
    role: text("role"),
    status: text("status").default("pending").notNull(),
    expiresAt: timestamp("expires_at").notNull(),
    createdAt: timestamp("created_at").defaultNow().notNull(),
    inviterId: text("inviter_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
  },
  (table) => [
    index("mediaInvitation_organizationId_idx").on(table.organizationId),
    index("mediaInvitation_email_idx").on(table.email),
  ],
);

export const userRelations = relations(user, ({ many }) => ({
  sessions: many(session),
  accounts: many(account),
  memberships: many(membership),
  mediaInvitations: many(mediaInvitation),
}));

export const sessionRelations = relations(session, ({ one }) => ({
  user: one(user, {
    fields: [session.userId],
    references: [user.id],
  }),
}));

export const accountRelations = relations(account, ({ one }) => ({
  user: one(user, {
    fields: [account.userId],
    references: [user.id],
  }),
}));

export const mediaRelations = relations(media, ({ many }) => ({
  memberships: many(membership),
  mediaInvitations: many(mediaInvitation),
}));

export const membershipRelations = relations(membership, ({ one }) => ({
  media: one(media, {
    fields: [membership.organizationId],
    references: [media.id],
  }),
  user: one(user, {
    fields: [membership.userId],
    references: [user.id],
  }),
}));

export const mediaInvitationRelations = relations(
  mediaInvitation,
  ({ one }) => ({
    media: one(media, {
      fields: [mediaInvitation.organizationId],
      references: [media.id],
    }),
    user: one(user, {
      fields: [mediaInvitation.inviterId],
      references: [user.id],
    }),
  }),
);
