import assert from "node:assert/strict";
import test from "node:test";
import { PGlite } from "@electric-sql/pglite";
import { drizzle } from "drizzle-orm/pglite";
import { migrate } from "drizzle-orm/pglite/migrator";
import { eq } from "drizzle-orm";
import * as schema from "../db/schema";
import { identityRequestText, renderLogoArtwork, sameLogoRequest } from "../contracts/src/branding";
import type { BrandIdentity } from "../contracts/src/branding";

test("branding: real preview boundary, explicit current approval, validated upload, private brand brief and immutable live logo", async t => {
  process.env.DATABASE_DRIVER = "pglite";
  process.env.PGLITE_DATA_DIR = "unused-branding-test";
  process.env.BETTER_AUTH_SECRET = "branding-test-only-secret-at-least-32-characters";
  const client = new PGlite(); globalThis.__mediaCommandPglite = client;
  const database = drizzle({ client, schema }); await migrate(database, { migrationsFolder: "./db/migrations" });
  const { auth } = await import("../src/server/auth");
  const { handleApiRequest } = await import("../src/router");
  const { logoDesigner, logoArtworkSchema } = await import("../src/server/branding");
  const artwork = { background: "none", shapes: [{ path: "M32 32 L224 32 L128 224 Z", fill: "#b62434", stroke: "none", strokeWidth: 0 }] };
  let actor = "admin";
  t.mock.method(auth.api, "getSession", async () => actor === "anonymous" ? null : ({ user: { id: actor, name: actor, email: `${actor}@test.example` }, session: {} }));
  const inference = t.mock.method(logoDesigner, "infer", async () => artwork);
  const request = (path: string, body?: unknown, method = body ? "POST" : "GET") => handleApiRequest(new Request(`http://local.test/api/v1${path}`, { method, headers: { "content-type": "application/json" }, body: body ? JSON.stringify(body) : undefined }));
  const logoRequest = { name: "رسانهٔ آزمون", instructions: "نشان خبری ساده با خطوط روشن و منظم", primaryColor: "#b62434", secondaryColor: "#ef4444", backgroundColor: "#ffffff", identity: "" };
  const design = { style: "مدرن", referenceWebsite: "", contentDensity: "متعادل", colorScheme: "روشن", primaryColor: logoRequest.primaryColor, secondaryColor: logoRequest.secondaryColor, backgroundColor: logoRequest.backgroundColor, logoMode: "generate", visualIdentity: "هویت بصری مشخص ندارم", fontPreference: "Vazirmatn", logoInstructions: logoRequest.instructions, logoDraft: { request: logoRequest, artwork, approved: true } };
  const brief = { mediaTopics: ["عمومی"], targetAudience: ["عموم مردم"], languages: ["فارسی"], categories: ["خبر"], categoryIds: ["branding-category"], contentTypes: ["خبر"], homepageFocus: ["آخرین اخبار"], features: ["جستجو"], additionalNotes: "توضیح خصوصی", design };
  const spec = { title: logoRequest.name, tagline: "", language: "fa", accent: "#b62434", layout: "lead", footer: "", blocks: [{ id: "latest", title: "آخرین خبرها", sectionIds: [], limit: 8 }], designBrief: brief };
  const input = { name: logoRequest.name, slug: "branding-site", spec };
  try {
    await database.insert(schema.user).values(["admin", "outsider"].map(id => ({ id, name: id, email: `${id}@test.example` })));
    await database.insert(schema.mediaAdmin).values({ userId: "admin" });
    actor = "anonymous"; assert.equal((await request("/media/logo-preview", logoRequest)).status, 401);
    actor = "outsider"; assert.equal((await request("/media/logo-preview", logoRequest)).status, 403);
    actor = "admin";
    assert.equal((await request("/media/logo-preview", { ...logoRequest, instructions: "" })).status, 400);
    const preview = await request("/media/logo-preview", logoRequest);
    assert.equal(preview.status, 200, await preview.clone().text());
    assert.equal((await preview.json()).data.dataUrl, renderLogoArtwork(artwork));
    assert.equal(inference.mock.callCount(), 1);
    assert.equal((await request("/media/logo-preview", logoRequest)).status, 429);
    assert.equal(logoArtworkSchema.safeParse({ ...artwork, shapes: [{ ...artwork.shapes[0], path: '<script>alert(1)</script>' }] }).success, false);
    assert.equal(logoArtworkSchema.safeParse({ ...artwork, background: "url(https://untrusted.example)" }).success, false);
    assert.ok(!sameLogoRequest(logoRequest, { ...logoRequest, primaryColor: "#ffffff" }));
    const identity: BrandIdentity = { description: "شخصیت رسانه دقیق و مستقل است", colorRules: "قرمز فقط برای تأکید استفاده شود", typography: "تیترهای واضح با فونت وزیرمتن", imagery: "تصاویر مستند و ساده و بدون اغراق", layout: "چیدمان منظم با فضای خالی کافی", restrictions: "", referenceUrl: "" };
    assert.equal(identityRequestText(identity), identityRequestText({ ...identity, description: `  ${identity.description}  ` }));
    await database.insert(schema.media).values(["m1", "m2"].map(id => ({ id, name: id, slug: id, createdAt: new Date() })));
    await database.insert(schema.mediaCreationRequest).values(["m1", "m2"].map(mediaId => ({ mediaId, status: "approved" as const })));
    await database.insert(schema.membership).values({ id: "owner", userId: "admin", organizationId: "m1", role: "owner", createdAt: new Date() });
    await database.insert(schema.platformCategory).values({ id: "branding-category", key: "branding-category", nameFa: "خبر", nameEn: "News", nameAr: "خبر" });
    const withDesign = (change: Record<string, unknown>) => ({ ...input, spec: { ...spec, designBrief: { ...brief, design: { ...design, ...change } } } });
    assert.equal((await request("/sites", withDesign({ logoDraft: { ...design.logoDraft, approved: false } }))).status, 400);
    assert.equal((await request("/sites", withDesign({ primaryColor: "#ffffff" }))).status, 400);
    assert.equal((await request("/sites", withDesign({ logoInstructions: "توضیح تازه و تغییر سبک لوگو" }))).status, 400);
    assert.equal((await request("/sites", withDesign({ visualIdentity: "هویت بصری مشخص دارم" }))).status, 400);
    const created = await request("/sites", input);
    assert.equal(created.status, 201, await created.clone().text());
    const { id } = (await created.json()).data;
    const [saved] = await database.select().from(schema.mediaSite).where(eq(schema.mediaSite.id, id));
    assert.equal(saved.spec.logo, renderLogoArtwork(artwork));
    const [media] = await database.select().from(schema.media).where(eq(schema.media.id, "m1"));
    assert.equal(media.logo, saved.spec.logo);
    const [otherMedia] = await database.select().from(schema.media).where(eq(schema.media.id, "m2"));
    assert.equal(otherMedia.logo, null);
    assert.equal((await request(`/sites/${id}/lifecycle`, { expectedRevision: 1, action: "activate" })).status, 200);
    const publicPage = (await (await request("/public/sites/branding-site")).json()).data;
    assert.equal(publicPage.site.spec.logo, saved.spec.logo);
    assert.equal(publicPage.site.spec.designBrief, undefined);
    const png = "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jf1sAAAAASUVORK5CYII=";
    const uploaded = { ...withDesign({ logoMode: "provided", logoData: png, logoDraft: undefined, visualIdentity: "هویت بصری مشخص دارم", identityDetails: identity }), expectedRevision: 2 };
    const update = await request(`/sites/${id}`, uploaded, "PATCH");
    assert.equal(update.status, 200, await update.clone().text());
    const [updated] = await database.select().from(schema.mediaSite).where(eq(schema.mediaSite.id, id));
    assert.equal(updated.spec.logo, png);
    assert.equal(updated.spec.designBrief!.design.logoData, undefined);
    assert.deepEqual(updated.spec.designBrief!.design.identityDetails, identity);
    const stillLive = (await (await request("/public/sites/branding-site")).json()).data;
    assert.equal(stillLive.site.spec.logo, saved.spec.logo);
    const invalidUpload = await request(`/sites/${id}`, { ...uploaded, expectedRevision: 3, spec: { ...uploaded.spec, designBrief: { ...uploaded.spec.designBrief, design: { ...uploaded.spec.designBrief.design, logoData: "data:image/png;base64,YWJjZA==" } } } }, "PATCH");
    assert.equal(invalidUpload.status, 400);
  } finally { await client.close(); globalThis.__mediaCommandPglite = undefined; }
});
