import assert from "node:assert/strict";
import test from "node:test";
import { PGlite } from "@electric-sql/pglite";
import { drizzle } from "drizzle-orm/pglite";
import { migrate } from "drizzle-orm/pglite/migrator";
import { eq } from "drizzle-orm";
import * as schema from "../db/schema";

test("media approval: final submission, scoped status, super-admin review and server-side site/source gates", async t => {
  process.env.DATABASE_DRIVER = "pglite"; process.env.PGLITE_DATA_DIR = "unused-media-request-test";
  process.env.BETTER_AUTH_SECRET = "media-request-test-only-secret-at-least-32-characters";
  const client = new PGlite(); globalThis.__mediaCommandPglite = client;
  const database = drizzle({ client, schema }); await migrate(database, { migrationsFolder: "./db/migrations" });
  const { auth } = await import("../src/server/auth"); const { handleApiRequest } = await import("../src/router");
  let actor: string | null = "owner";
  t.mock.method(auth.api, "getSession", async () => actor ? { user: { id: actor, name: actor, email: `${actor}@test.example` }, session: { activeOrganizationId: actor === "other" ? "m2" : "m1" } } : null);
  const request = (path: string, body?: unknown, method = body ? "POST" : "GET") => handleApiRequest(new Request(`http://local.test/api/v1${path}`, { method, headers: { "content-type": "application/json" }, body: body ? JSON.stringify(body) : undefined }));
  const data = async (response: Response, status = 200) => { assert.equal(response.status, status, await response.clone().text()); return (await response.json()).data; };
  const preferences = { editorialViewpoint: "خبرها با حفظ امانت و دقت بازنویسی شوند", sourceSelections: [], socialPlatforms: [], setupCompleted: false, setupStep: 1 };
  const siteInput = { name: "رسانهٔ آزمایشی", slug: "test-media", spec: { title: "رسانهٔ آزمایشی", tagline: "", language: "fa", accent: "#bb3344", layout: "lead", footer: "", blocks: [{ id: "news", title: "خبرها", sectionIds: [], limit: 5 }] } };
  try {
    await database.insert(schema.user).values(["super", "owner", "other"].map(id => ({ id, name: id === "owner" ? "رسانه‌دار" : id, email: `${id}@test.example` })));
    await database.insert(schema.platformAdmin).values({ userId: "super" });
    await database.insert(schema.media).values(["m1", "m2"].map(id => ({ id, name: id, slug: id, createdAt: new Date(), metadata: JSON.stringify({ setupPreferences: preferences }) })));
    await database.insert(schema.membership).values([["owner", "m1"], ["other", "m2"]].map(([userId, organizationId]) => ({ id: userId, userId, organizationId, role: "owner", createdAt: new Date() })));
    assert.equal((await data(await request("/media/request"))).status, "draft");
    await data(await request("/media/setup", preferences, "PATCH"));
    assert.equal((await database.select().from(schema.mediaCreationRequest)).length, 0);
    const site = await data(await request("/sites", siteInput), 201);
    await data(await request(`/sites/${site.id}/lifecycle`, { expectedRevision: 1, action: "activate" }), 403);
    await data(await request(`/sites/${site.id}/preview`), 403);
    // Legacy rows marked live cannot bypass the new media gate.
    await database.update(schema.mediaSite).set({ status: "live", liveSpec: siteInput.spec as typeof schema.mediaSite.$inferInsert.spec }).where(eq(schema.mediaSite.id, site.id));
    await data(await request("/public/sites/test-media"), 404);
    await data(await request("/public/sites/test-media/sitemap"), 404);
    await database.update(schema.mediaSite).set({ status: "draft", liveSpec: null }).where(eq(schema.mediaSite.id, site.id));
    assert.equal((await request("/platform/media-requests")).status, 403);
    await data(await request("/media/source-access-requests", { sourceType: "website", url: "https://source.test/", categoryMode: "all", categoryIds: [] }), 201);
    await database.insert(schema.platformCategory).values({ id: "politics", key: "media-request-test-politics", nameFa: "سیاسی", nameEn: "Politics", nameAr: "سياسة" });
    await data(await request("/media/source-access-requests", { sourceType: "website", url: "https://selected.test/", categoryMode: "selected", categoryIds: ["politics"] }), 201);
    await data(await request("/media/source-access-requests", { sourceType: "social", url: "https://t.me/test_media" }), 201);
    await data(await request("/media/setup", { ...preferences, setupCompleted: true, setupStep: 4 }, "PATCH"));
    assert.equal((await data(await request("/media/request"))).status, "pending");
    await data(await request(`/sites/${site.id}`, { ...siteInput, expectedRevision: 1 }, "PATCH"), 403);
    await data(await request("/publications", { siteId: site.id, versionId: "missing" }), 403);
    actor = "super";
    const list = await data(await request("/platform/media-requests"));
    assert.equal(list.pending, 1); assert.equal(list.rows[0].requestedBy, "رسانه‌دار"); assert.equal(list.rows[0].sites[0].slug, "test-media");
    const requestedSources = list.rows[0].sources;
    assert.equal(requestedSources.find((source: { url: string }) => source.url === "https://source.test/").categoryMode, "all");
    assert.deepEqual(requestedSources.find((source: { url: string }) => source.url === "https://selected.test/").categories, [{ id: "politics", name: "سیاسی" }]);
    assert.equal(requestedSources.find((source: { url: string }) => source.url === "https://selected.test/").categoryMode, "selected");
    assert.equal(requestedSources.find((source: { sourceType: string }) => source.sourceType === "social").categoryMode, null);
    const sources = await data(await request("/platform/source-access-requests"));
    assert.equal(sources[0].mediaApproved, false);
    await data(await request(`/platform/source-access-requests/${sources[0].id}`, { action: "reject" }, "PATCH"), 409);
    actor = "owner";
    await data(await request("/platform/media-requests/m1", { action: "approve", expectedRevision: 1 }, "PATCH"), 403);
    actor = "other";
    assert.equal((await data(await request("/media/request?mediaId=m1"))).status, "draft");
    actor = "super";
    const results = await Promise.all([request("/platform/media-requests/m1", { action: "approve", expectedRevision: 1 }, "PATCH"), request("/platform/media-requests/m1", { action: "approve", expectedRevision: 1 }, "PATCH")]);
    assert.deepEqual(results.map(row => row.status).sort(), [200, 409]);
    assert.equal((await database.select().from(schema.mediaCreationRequest).where(eq(schema.mediaCreationRequest.mediaId, "m1")))[0].status, "approved");
    await data(await request(`/platform/source-access-requests/${sources[0].id}`, { action: "reject" }, "PATCH"));
    actor = "owner";
    await data(await request("/media/setup", { ...preferences, setupCompleted: true }, "PATCH"));
    assert.equal((await data(await request("/media/request"))).status, "approved");
    await data(await request(`/sites/${site.id}/lifecycle`, { expectedRevision: 1, action: "activate" }));
    await data(await request(`/sites/${site.id}/preview`));
    actor = null; await data(await request("/public/sites/test-media"));
    actor = "other";
    await data(await request("/media/setup", { ...preferences, setupCompleted: true }, "PATCH"));
    actor = "super";
    await data(await request("/platform/media-requests/m2", { action: "reject", expectedRevision: 1 }, "PATCH"), 400);
    await data(await request("/platform/media-requests/m2", { action: "reject", expectedRevision: 1, note: "اطلاعات رسانه ناقص است" }, "PATCH"));
    actor = "other";
    const rejected = await data(await request("/media/request")); assert.equal(rejected.status, "rejected"); assert.ok(rejected.reviewNote);
    await data(await request("/sites", { ...siteInput, slug: "rejected-site" }), 403);
    const events = await database.select().from(schema.auditEvent).where(eq(schema.auditEvent.action, "media.request.approved")); assert.equal(events.length, 1);
    await database.insert(schema.media).values([{ id: "legacy", name: "Legacy", slug: "legacy", createdAt: new Date(), metadata: JSON.stringify({ setupPreferences: { ...preferences, setupCompleted: true } }) }, { id: "draft", name: "Draft", slug: "draft", createdAt: new Date(), metadata: JSON.stringify({ setupPreferences: preferences }) }]);
    await database.insert(schema.membership).values({ id: "legacy-owner", userId: "owner", organizationId: "legacy", role: "owner", createdAt: new Date() });
    const { enrollCompletedMediaRequests } = await import("../src/server/media-requests");
    await enrollCompletedMediaRequests(); await enrollCompletedMediaRequests();
    const enrolled = await database.select().from(schema.mediaCreationRequest);
    assert.equal(enrolled.length, 3); assert.equal(enrolled.find(row => row.mediaId === "legacy")?.status, "pending");
    assert.equal(enrolled.find(row => row.mediaId === "legacy")?.requestedBy, "owner");
    assert.equal(enrolled.find(row => row.mediaId === "m1")?.status, "approved");
    assert.equal(enrolled.find(row => row.mediaId === "m2")?.status, "rejected");
  } finally { await client.close(); }
});

