    await distributeRawArticleToSubscribers("catalog-only", "raw-2", "new");
    assert.equal((await database.select().from(schema.mediaInboxItem)).length, 1);
    assert.equal((await request("sources/catalog-only/visibility", "PATCH", { mode: "public" })).status, 200);
    await distributeRawArticleToSubscribers("catalog-only", "raw-3", "new");
