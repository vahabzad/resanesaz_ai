    assert.equal((await request("sources/catalog-only/visibility", "PATCH", { mode: "catalog_hidden" })).status, 200);
    assert.equal((await getSourcesWorkspace("media-test")).sources.length, 1);
    assert.equal(await subscribeSource(subscribeInput), null);
    for (const id of ["raw-1", "raw-2", "raw-3"]) await database.insert(schema.rawArticle).values({ id, sourceId: "catalog-only", crawlRunId: "run-test", canonicalUrl: `https://example.test/${id}`, title: id, contentHash: id });
